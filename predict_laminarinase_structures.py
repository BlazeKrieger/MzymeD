#!/usr/bin/env python3
"""
Structure prediction pipeline for laminarinase sequences.
1. Reads all FASTA files from laminarinases directory
2. Predicts 3D structures using ESMFold
3. Saves predicted structures as PDB files
4. Runs activity assessment on predictions
"""

import os
import json
from pathlib import Path
from Bio import SeqIO
import subprocess
import sys

LAMINARINASES_DIR = Path("laminarinases")
PREDICTED_STRUCTURES_DIR = Path("predicted_structures")
PREDICTIONS_LOG = Path("structure_predictions.json")

PREDICTED_STRUCTURES_DIR.mkdir(exist_ok=True)

def find_all_fasta_files():
    """Recursively find all FASTA files in laminarinases directory."""
    fasta_files = []
    
    for root, dirs, files in os.walk(LAMINARINASES_DIR):
        for file in files:
            if file.endswith(('.fasta', '.fa', '.faa')):
                full_path = Path(root) / file
                fasta_files.append(full_path)
    
    return sorted(fasta_files)

def parse_fasta_file(fasta_file):
    """Parse FASTA file and extract sequences."""
    sequences = []
    
    try:
        for record in SeqIO.parse(str(fasta_file), "fasta"):
            sequences.append({
                'id': record.id,
                'description': record.description,
                'sequence': str(record.seq),
                'length': len(record.seq)
            })
    except Exception as e:
        print(f"Error parsing {fasta_file}: {e}")
        return None
    
    return sequences

def predict_structure_esmfold(sequence, protein_id, output_pdb):
    """
    Predict protein structure using ESMFold via OmegaFold or local installation.
    ESMFold is faster than AlphaFold2 and requires less memory.
    
    Falls back to a simpler approach if ESMFold is not available.
    """
    
    # Try using OmegaFold (faster alternative to AlphaFold2)
    try:
        # Create a temporary FASTA file
        temp_fasta = PREDICTED_STRUCTURES_DIR / f"temp_{protein_id}.fasta"
        with open(temp_fasta, 'w') as f:
            f.write(f">{protein_id}\n{sequence}\n")
        
        # Try ESMFold first (if installed)
        try:
            result = subprocess.run(
                ["esmfold", "infer", str(temp_fasta), "-o", str(output_pdb)],
                capture_output=True,
                timeout=300
            )
            if result.returncode == 0:
                temp_fasta.unlink()
                return True
        except (FileNotFoundError, subprocess.TimeoutExpired):
            pass
        
        # Try OmegaFold
        try:
            result = subprocess.run(
                ["omegafold", str(temp_fasta), str(PREDICTED_STRUCTURES_DIR)],
                capture_output=True,
                timeout=300
            )
            if result.returncode == 0:
                temp_fasta.unlink()
                return True
        except (FileNotFoundError, subprocess.TimeoutExpired):
            pass
        
        # Fallback: Use ColabFold API (online)
        return predict_with_colabfold(sequence, protein_id, output_pdb)
        
    except Exception as e:
        print(f"Error predicting structure for {protein_id}: {e}")
        return False

